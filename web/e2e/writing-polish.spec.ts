import { expect, test } from "@playwright/test";
import { accountsSession, runAccounts, sameOrigin, signIn } from "./support";
import { docSyncState } from "./doc-support";

test("Suggester invitation, inline accept and reject, and persisted normal text", async ({ browser }) => {
  const owner = await accountsSession(browser, "carbon", { reducedMotion: "reduce" });
  const guest = await accountsSession(browser, "friend", { reducedMotion: "reduce" });
  const page = await owner.newPage(), friend = await guest.newPage();
  page.setDefaultTimeout(15_000);
  try {
    await signIn(page, runAccounts().carbon.email, "/library");
    const response = await page.request.post('/api/v1/docs', { headers: sameOrigin(), data: { title: `Review ${Date.now()}`, markdown: 'The original line.\n' } });
    expect(response.status()).toBe(201);
    const doc = await response.json();
    await page.goto(`/d/${doc.id}`);
    await expect(docSyncState(page)).toHaveAccessibleName("Connected and synced");
    await expect(page.getByRole('toolbar', { name: 'Formatting' })).toBeVisible();
    await page.getByRole('button', { name: 'Share', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Share', exact: true });
    await dialog.getByRole('textbox', { name: 'Who to share with' }).fill(runAccounts().friend.id);
    await dialog.getByRole('combobox', { name: 'Role', exact: true }).click();
    await page.getByRole('option', { name: 'Suggester', exact: true }).click();
    await expect(dialog).toContainText('Can comment and suggest changes');
    await dialog.getByRole('button', { name: 'Share', exact: true }).click();
    await expect(dialog.getByRole('combobox', { name: `Role of ${runAccounts().friend.id}` })).toContainText('Suggester');
    await page.keyboard.press('Escape');
    await signIn(friend, runAccounts().friend.email, `/d/${doc.id}`);
    await expect(friend.getByRole('button', { name: 'Mode: Suggesting' })).toBeVisible();
    const editor = friend.locator('.ProseMirror[contenteditable="true"]');
    await editor.click();
    await editor.press('ControlOrMeta+End');
    await friend.keyboard.type(' Added thought.');
    await expect(editor.locator('ins')).toContainText('Added thought.');
    await expect(docSyncState(friend)).toHaveAccessibleName('Connected and synced');
    const suggestions = await page.request.get(`/api/v1/docs/${doc.id}/suggestions`);
    const id = (await suggestions.json()).suggestions[0].id;
    const refused = await friend.request.post(`/api/v1/docs/${doc.id}/suggestions/${id}/accept`, { headers: sameOrigin() });
    expect(refused.status()).toBe(403);
    const editRefused = await friend.request.patch(`/api/v1/docs/${doc.id}`, { headers: sameOrigin(), data: { title: 'Cannot rename as suggester' } });
    expect(editRefused.status()).toBe(403);
    expect((await (await page.request.get(`/api/v1/docs/${doc.id}/markdown`)).json()).markdown).toBe('The original line.\n');
    await page.locator('.ProseMirror ins').first().click();
    const card = page.getByRole('dialog', { name: 'Review suggestion' });
    await expect(card).toContainText('Added thought.');
    await card.getByRole('button', { name: 'Accept', exact: true }).click();
    await expect(page.locator('.ProseMirror ins')).toHaveCount(0);
    await expect(page.locator('.ProseMirror')).toContainText('The original line. Added thought.');
    await editor.click();
    await editor.press('ControlOrMeta+End');
    await friend.keyboard.type(' Remove this.');
    await expect(docSyncState(friend)).toHaveAccessibleName('Connected and synced');
    await page.locator('.ProseMirror ins').first().click();
    await expect(card).toBeVisible();
    await card.getByRole('button', { name: 'Reject', exact: true }).click();
    await expect(page.locator('.ProseMirror')).not.toContainText('Remove this.');
    await page.reload();
    await expect(docSyncState(page)).toHaveAccessibleName('Connected and synced');
    await expect(page.locator('.ProseMirror')).toContainText('The original line. Added thought.');
    expect((await (await page.request.get(`/api/v1/docs/${doc.id}/markdown`)).json()).markdown).toBe('The original line. Added thought.\n');
    await expect(page.locator('.ProseMirror [data-suggestion]')).toHaveCount(0);
  } finally { await owner.close(); await guest.close(); }
});

test("selection menu, neutral surfaces, independent submenu highlights, and anchored slash menu", async ({ browser }) => {
  const context = await accountsSession(browser, 'carbon', { reducedMotion: 'reduce', viewport: { width: 1100, height: 720 } });
  const page = await context.newPage();
  page.setDefaultTimeout(15_000);
  try {
    await signIn(page, runAccounts().carbon.email, '/library');
    const response = await page.request.post('/api/v1/docs', { headers: sameOrigin(), data: { title: `Menus ${Date.now()}`, markdown: 'Alpha beta gamma.\n\n' + 'A line to scroll past.\n\n'.repeat(28) } });
    const doc = await response.json();
    await page.goto(`/d/${doc.id}`);
    await expect(docSyncState(page)).toHaveAccessibleName('Connected and synced');
    const editor = page.locator('.ProseMirror');
    await expect(page.getByRole('toolbar', { name: 'Formatting' })).toBeVisible();
    const palette = await page.evaluate(() => { const s=getComputedStyle(document.documentElement); return ['--background','--surface-muted','--surface-pressed'].map((k,i)=>s.getPropertyValue(k).trim() === s.getPropertyValue(['--neutral-0','--neutral-2','--neutral-3'][i]).trim()); });
    expect(palette).toEqual([true, true, true]);
    await editor.locator('p').first().dblclick({ position: { x: 25, y: 12 } });
    const menu = page.getByRole('menu', { name: 'Text actions' });
    await expect(menu).toBeVisible();
    await menu.getByRole('menuitem', { name: 'Bold', exact: true }).click();
    await expect(editor.locator('strong')).toHaveText('Alpha');
    await editor.locator('strong').click({ button: 'right' });
    await expect(menu).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(editor).toBeFocused();
    await page.getByRole('button', { name: 'More', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Download as', exact: true }).hover();
    const rtf = page.getByRole('menuitem', { name: 'Rich text (.rtf)', exact: true });
    await expect(rtf).toBeVisible();
    await rtf.hover();
    const main = page.getByRole('menuitem', { name: 'Download as', exact: true });
    const highlight = await main.evaluate(el => { const parent=el.closest('[role="menu"]')!; const h=parent.querySelector('[class*="highlight"]')!; return { actual: h.getBoundingClientRect().top, expected: el.getBoundingClientRect().top }; });
    expect(Math.abs(highlight.actual-highlight.expected)).toBeLessThan(2);
    await page.keyboard.press('Escape'); await page.keyboard.press('Escape');
    await editor.click(); await editor.press('ControlOrMeta+End'); await editor.press('Enter'); await page.keyboard.type('/');
    const list = page.getByRole('listbox', { name: 'Insert', exact: true });
    await expect(list).toBeVisible();
    const before = await list.boundingBox();
    expect(before!.y).toBeGreaterThanOrEqual(0); expect(before!.y+before!.height).toBeLessThanOrEqual(720);
    await page.mouse.move(100, 600); await page.mouse.wheel(0,-100);
    await expect.poll(async () => (await list.boundingBox())!.y).not.toBe(before!.y);
    const pageY = await page.evaluate(()=>window.scrollY);
    await list.hover(); await page.mouse.wheel(0,600);
    await expect.poll(async () => await list.evaluate(el=>el.scrollTop)).toBeGreaterThan(0);
    expect(await page.evaluate(()=>window.scrollY)).toBe(pageY);
    await page.getByRole('option', { name: 'Footnote', exact: true }).click();
    await expect(list).toHaveCount(0);
    await expect(editor.locator('[data-footnote]')).not.toHaveCount(0);
  } finally { await context.close(); }
});
